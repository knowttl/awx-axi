import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { DOMAINS } from "../dist/cli.js";

const help = (args: string[]) => execFileSync(process.execPath, ["dist/bin/awx-axi.js", ...args, "--help"], { encoding: "utf8" }).trim();
const core = ["auth", "doctor", "config", "profile", "setup", "update"];
const rows = [
  ["auth", "login, status, logout"],
  ["doctor", "credential permissions and controller identity"],
  ["config", "path"],
  ["profile", "list"],
  ["setup", "hooks"],
  ["update", "upgrade; --check reports the latest version"],
  ...DOMAINS.map((domain) => [domain.name, domain.subcommands.map((command) => command.name).join(", ")]),
];
const table = ["| Command | Operations |", "| --- | --- |", ...rows.map(([name, operations]) => `| \`${name}\` | ${operations} |`)].join("\n");
const sections = core.map((name) => `## ${name}\n\n\`\`\`text\n${help([name])}\n\`\`\``);
const contents = [...core, ...DOMAINS.map((domain) => domain.name)]
  .map((name) => `- [${name}](#${name})`).join("\n");
for (const domain of DOMAINS) {
  sections.push(`## ${domain.name}\n\n\`\`\`text\n${help([domain.name])}\n\`\`\``);
  for (const command of domain.subcommands) {
    sections.push(`### ${domain.name} ${command.name}\n\n\`\`\`text\n${help([domain.name, command.name])}\n\`\`\``);
  }
}
const reference = `<!-- Generated by scripts/command-reference.ts. Do not edit. -->\n# Command reference\n\n${contents}\n\nRegenerate with \`npm run docs:commands\` after building.\n\n${table}\n\n${sections.join("\n\n")}\n`;
const path = "docs/commands.md";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== reference) throw new Error(`${path} is stale; run npm run docs:commands`);
} else {
  writeFileSync(path, reference);
}
